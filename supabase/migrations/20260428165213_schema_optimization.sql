-- =============================================================================
-- Schema Optimization Migration
-- =============================================================================
-- Fixes: participation merge, event_media PK, timestamps, date→starts_at,
--        numeric→integer, location nullable, RLS policies, grants
-- =============================================================================

-- ─── 1. Merge participation into event_participation ────────────────────────

ALTER TABLE public.event_participation
  ADD COLUMN status public.invitation_status_enum DEFAULT 'Pending'::public.invitation_status_enum;

UPDATE public.event_participation ep
SET status = p.status
FROM public.participation p
WHERE p.event_participation_id = ep.event_participation_id;

ALTER TABLE public.ticket DROP CONSTRAINT IF EXISTS ticket_event_participation_id_fkey;
ALTER TABLE public.ticket
  ADD CONSTRAINT ticket_event_participation_id_fkey
  FOREIGN KEY (event_participation_id)
  REFERENCES public.event_participation(event_participation_id) ON DELETE CASCADE;

DROP TABLE IF EXISTS public.participation;

-- ─── 2. event_media: replace media_url PK with auto-increment media_id ──────

ALTER TABLE public.event_media
  ADD COLUMN media_id integer GENERATED BY DEFAULT AS IDENTITY;

ALTER TABLE public.event_media DROP CONSTRAINT event_media_pkey;
ALTER TABLE public.event_media ADD PRIMARY KEY (media_id);

-- ─── 3. Timestamps: without time zone → with time zone ──────────────────────

-- event
ALTER TABLE public.event
  ALTER COLUMN created_at TYPE timestamptz USING created_at AT TIME ZONE 'UTC',
  ALTER COLUMN updated_at TYPE timestamptz USING updated_at AT TIME ZONE 'UTC';

-- event_participation
ALTER TABLE public.event_participation
  ALTER COLUMN created_at TYPE timestamptz USING created_at AT TIME ZONE 'UTC';

-- location
ALTER TABLE public.location
  ALTER COLUMN created_at TYPE timestamptz USING created_at AT TIME ZONE 'UTC',
  ALTER COLUMN updated_at TYPE timestamptz USING updated_at AT TIME ZONE 'UTC';

-- person
ALTER TABLE public.person
  ALTER COLUMN created_at TYPE timestamptz USING created_at AT TIME ZONE 'UTC',
  ALTER COLUMN updated_at TYPE timestamptz USING updated_at AT TIME ZONE 'UTC';

-- ticket
ALTER TABLE public.ticket
  ALTER COLUMN issued_at TYPE timestamptz USING issued_at AT TIME ZONE 'UTC',
  ALTER COLUMN redeemed_at TYPE timestamptz USING redeemed_at AT TIME ZONE 'UTC';

-- ─── 4. event.date → event.starts_at (timestamptz) + new ends_at ────────────

ALTER TABLE public.event
  ALTER COLUMN date TYPE timestamptz USING date AT TIME ZONE 'UTC';

ALTER TABLE public.event RENAME COLUMN date TO starts_at;

ALTER TABLE public.event ADD COLUMN ends_at timestamptz;

DROP INDEX IF EXISTS public.idx_event_date;
CREATE INDEX idx_event_starts_at ON public.event USING btree (starts_at);

-- ─── 5. numeric → integer ───────────────────────────────────────────────────

ALTER TABLE public.event
  ALTER COLUMN max_capacity TYPE integer USING max_capacity::integer;

ALTER TABLE public.event
  ADD CONSTRAINT chk_max_capacity_positive CHECK (max_capacity > 0);

ALTER TABLE public.ticket
  ALTER COLUMN scan_count TYPE integer USING scan_count::integer;

-- ─── 6. location: make address fields nullable ──────────────────────────────

ALTER TABLE public.location ALTER COLUMN street DROP NOT NULL;
ALTER TABLE public.location ALTER COLUMN house_number DROP NOT NULL;
ALTER TABLE public.location ALTER COLUMN postal_code DROP NOT NULL;
ALTER TABLE public.location ALTER COLUMN country DROP NOT NULL;

-- ─── 7. RLS: enable on all tables ──────────────────────────────────────────

ALTER TABLE public.event ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.event_participation ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.location ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ticket ENABLE ROW LEVEL SECURITY;
-- event_media and person already have RLS enabled

-- ─── 8. Grants: restrict anon and authenticated ─────────────────────────────

REVOKE ALL ON ALL TABLES IN SCHEMA public FROM anon;
REVOKE ALL ON ALL TABLES IN SCHEMA public FROM authenticated;

-- anon: read-only on public-facing tables
GRANT SELECT ON public.event TO anon;
GRANT SELECT ON public.location TO anon;
GRANT SELECT ON public.event_media TO anon;
GRANT SELECT ON public.event_participation TO anon;
GRANT SELECT ON public.person TO anon;

-- authenticated: read + write (no DELETE/TRUNCATE)
GRANT SELECT, INSERT, UPDATE ON public.event TO authenticated;
GRANT SELECT, INSERT, UPDATE ON public.location TO authenticated;
GRANT SELECT, INSERT, UPDATE ON public.event_media TO authenticated;
GRANT SELECT, INSERT, UPDATE ON public.event_participation TO authenticated;
GRANT SELECT, INSERT, UPDATE ON public.person TO authenticated;
GRANT SELECT, INSERT, UPDATE ON public.ticket TO authenticated;

-- sequences (needed for INSERT with auto-increment PKs)
GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO authenticated;
GRANT USAGE ON ALL SEQUENCES IN SCHEMA public TO anon;

-- service_role keeps full access (Supabase default, not revoked)

-- ─── 9. RLS Policies ────────────────────────────────────────────────────────

-- event
CREATE POLICY "anon_select_public_events" ON public.event
  FOR SELECT TO anon USING (is_public = true);
CREATE POLICY "auth_select_events" ON public.event
  FOR SELECT TO authenticated USING (true);
CREATE POLICY "auth_insert_events" ON public.event
  FOR INSERT TO authenticated WITH CHECK (true);
CREATE POLICY "auth_update_events" ON public.event
  FOR UPDATE TO authenticated USING (true);

-- location
CREATE POLICY "select_locations" ON public.location
  FOR SELECT USING (true);
CREATE POLICY "insert_locations" ON public.location
  FOR INSERT TO authenticated WITH CHECK (true);

-- event_media
CREATE POLICY "select_media" ON public.event_media
  FOR SELECT USING (true);
CREATE POLICY "insert_media" ON public.event_media
  FOR INSERT TO authenticated WITH CHECK (true);

-- event_participation
CREATE POLICY "select_participation" ON public.event_participation
  FOR SELECT USING (true);
CREATE POLICY "insert_participation" ON public.event_participation
  FOR INSERT TO authenticated WITH CHECK (true);

-- person
CREATE POLICY "select_person" ON public.person
  FOR SELECT USING (true);
CREATE POLICY "auth_insert_person" ON public.person
  FOR INSERT TO authenticated WITH CHECK (true);
CREATE POLICY "auth_update_person" ON public.person
  FOR UPDATE TO authenticated USING (true);

-- ticket
CREATE POLICY "auth_select_ticket" ON public.ticket
  FOR SELECT TO authenticated USING (true);
CREATE POLICY "auth_insert_ticket" ON public.ticket
  FOR INSERT TO authenticated WITH CHECK (true);
